#!/usr/bin/env bash
# zim-claude-update.sh — bring an installed zim-claude up to date, quietly.
#
#   zim-claude (the wrapper) starts this detached before handing off to claude.
#   It is also safe to run by hand:
#
#       zim-claude-update.sh
#
# What it does:
#   1. rate-limits itself (default: at most once an hour)
#   2. takes a lock, so two sessions cannot update at the same time
#   3. refuses a checkout with local changes
#   4. fetches the recorded branch and fast-forwards ONLY
#   5. re-runs the checkout's install.sh, which installs atomically
#
# What it deliberately does NOT do:
#   - block or delay claude: the wrapper runs it detached
#   - report failure to the caller: every outcome is a log line and exit 0
#   - force, reset, stash or merge: a diverged checkout is left alone
#   - restart the proxy: a running session keeps its proxy and config
#
# Configuration (written by install.sh, at ~/.local/share/zim-claude/update.conf):
#
#   ZIM_CLAUDE_AUTO_UPDATE=1|0
#   ZIM_CLAUDE_REPO_DIR="/path/to/checkout"
#   ZIM_CLAUDE_REPO_BRANCH="main"
#
# Environment overrides:
#
#   ZIM_CLAUDE_NO_UPDATE=1          the wrapper skips this script entirely
#   ZIM_CLAUDE_UPDATE_INTERVAL=3600 seconds between checks (0 = every run)
#   ZIM_CLAUDE_UPDATE_FORCE=1       ignore the interval
#   ZIM_CLAUDE_UPDATE_TIMEOUT=20    seconds allowed for git fetch
#   ZIM_CLAUDE_STATE_DIR=...        state directory (tests)
#   ZIM_CLAUDE_UPDATE_CONF=...      config path (tests)
#   ZIM_CLAUDE_UPDATE_LOG=...       log path (tests)

set -uo pipefail

STATE_DIR="${ZIM_CLAUDE_STATE_DIR:-${XDG_DATA_HOME:-$HOME/.local/share}/zim-claude}"
CONF="${ZIM_CLAUDE_UPDATE_CONF:-$STATE_DIR/update.conf}"
LOG="${ZIM_CLAUDE_UPDATE_LOG:-$STATE_DIR/update.log}"
STAMP="$STATE_DIR/last-update-check"
LOCK="$STATE_DIR/update.lock"
INTERVAL="${ZIM_CLAUDE_UPDATE_INTERVAL:-3600}"
FETCH_TIMEOUT="${ZIM_CLAUDE_UPDATE_TIMEOUT:-20}"

mkdir -p -- "$STATE_DIR" 2>/dev/null || exit 0
chmod 700 -- "$STATE_DIR" 2>/dev/null || true

# Keep the log bounded. It is appended to, never read by the wrapper.
if [[ -f "$LOG" ]] && (( $(stat -c%s "$LOG" 2>/dev/null || echo 0) > 262144 )); then
  mv -f -- "$LOG" "$LOG.1" 2>/dev/null || true
fi

log() {
  printf '%s %s\n' "$(date '+%Y-%m-%dT%H:%M:%S%z')" "$*" >>"$LOG" 2>/dev/null || true
}

stamp() {
  printf '%s\n' "$(date +%s)" >"$STAMP" 2>/dev/null || true
}

# Serialize. Without this, two sessions started at once would both fetch and
# both run the installer; the second would find a half-written tree.
if command -v flock >/dev/null 2>&1; then
  exec 9>"$LOCK" 2>/dev/null || exit 0
  flock -n 9 || exit 0
fi

# Rate limit. A fresh install has no stamp, so the first run checks once.
if [[ "${ZIM_CLAUDE_UPDATE_FORCE:-0}" != "1" && -f "$STAMP" ]]; then
  last="$(cat "$STAMP" 2>/dev/null || true)"
  [[ "$last" =~ ^[0-9]+$ ]] || last=0
  now="$(date +%s)"
  if (( now - last < INTERVAL )); then
    exit 0
  fi
fi

if [[ ! -r "$CONF" ]]; then
  log "update.conf missing — auto-update is not configured"
  exit 0
fi

# shellcheck disable=SC1090  # generated by install.sh, fixed shape
. "$CONF"

if [[ "${ZIM_CLAUDE_AUTO_UPDATE:-0}" != "1" ]]; then
  exit 0
fi

repo="${ZIM_CLAUDE_REPO_DIR:-}"
branch="${ZIM_CLAUDE_REPO_BRANCH:-}"

if [[ -z "$repo" || -z "$branch" || "$branch" == "HEAD" ]]; then
  log "auto-update is not configured for this install (detached or non-git)"
  exit 0
fi
if [[ ! -d "$repo/.git" ]]; then
  log "checkout is gone: $repo — skipping"
  exit 0
fi
if ! command -v git >/dev/null 2>&1; then
  log "git not found — skipping"
  exit 0
fi

# Only tracked modifications block an update. Untracked files are allowed: if
# one would be overwritten, the fast-forward below fails and is logged.
dirty="$(git -C "$repo" status --porcelain --untracked-files=no 2>/dev/null || true)"
if [[ -n "$dirty" ]]; then
  log "checkout has local changes — not updating ($repo)"
  exit 0
fi

# `timeout` is not on every box (notably stock macOS), so fall back to a plain
# call there. The wrapper is detached either way, so this only bounds the
# updater's own lifetime.
run_git() {
  if command -v timeout >/dev/null 2>&1; then
    timeout "$FETCH_TIMEOUT" git "$@"
  else
    git "$@"
  fi
}

if ! run_git -C "$repo" fetch --quiet origin "$branch" >>"$LOG" 2>&1; then
  log "fetch failed for origin/$branch — will retry after the interval"
  stamp
  exit 0
fi

local_rev="$(git -C "$repo" rev-parse HEAD 2>/dev/null || true)"
remote_rev="$(git -C "$repo" rev-parse "refs/remotes/origin/$branch" 2>/dev/null || true)"

if [[ -z "$local_rev" || -z "$remote_rev" ]]; then
  log "could not resolve $branch revisions — skipping"
  stamp
  exit 0
fi
if [[ "$local_rev" == "$remote_rev" ]]; then
  log "already up to date (${local_rev:0:12})"
  stamp
  exit 0
fi

# Fast-forward only. A local commit, a rewritten history or a force-push all
# land here and are left for the user to resolve.
if ! git -C "$repo" merge-base --is-ancestor "$local_rev" "$remote_rev" 2>/dev/null; then
  log "local $branch has diverged from origin/$branch — not updating"
  stamp
  exit 0
fi
if ! git -C "$repo" merge --ff-only --quiet "$remote_rev" >>"$LOG" 2>&1; then
  log "fast-forward failed — not updating"
  stamp
  exit 0
fi

log "updated ${local_rev:0:12} -> ${remote_rev:0:12}"

# Install what was pulled. --no-venv keeps a missing venv from turning into a
# few-hundred-megabyte download in the background; --no-rc avoids rewriting the
# user's shell config from under them. stdin is closed so nothing can prompt.
if [[ -f "$repo/install.sh" ]]; then
  bash "$repo/install.sh" --no-venv --no-rc </dev/null >>"$LOG" 2>&1
  log "installer exited $?"
else
  log "no install.sh in $repo — files updated but not installed"
fi

stamp
exit 0
